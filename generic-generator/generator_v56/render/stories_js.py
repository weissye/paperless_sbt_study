def _long_dependency_is_credible(edge) -> bool:
    """Do not wire a weak cross-namespace key-name coincidence as a prerequisite.

    A top-level creator's own required field may happen to share a key name
    with a namespaced resource. Only this weak exact-name D2 inference is
    filtered; explicit nested paths, schema references and named IDs remain.
    """
    weak = {"D2:D_key_field_exact_match", "D2q:D_key_field_exact_match"}
    rules = {p.rule for p in edge.provenance}
    source = edge.source.strip("/")
    target = edge.target.strip("/")
    return not (rules and rules.issubset(weak) and "/" not in source and
                "/" in target and source != target.split("/")[-1])


def _long_create_key_alias(ep: EntityPlan) -> Optional[str]:
    """Use a unique required string returned by POST for a string path key.

    This is conservative: both the create request and the success response
    must document the same single required string, while the item's own path
    key is a distinct string absent from the create request.
    """
    if not ep.create_op or len(ep.key.fields) != 1 or not ep.entity.item_path:
        return None
    key = safe_identifier(ep.key.fields[0])
    if key in _required_js_fields(ep.create_op):
        return None
    path_params = [p for op in ep.ops for p in op.op.path_params
                   if safe_identifier(p.name) == key]
    if not path_params or any(p.schema.get("type") != "string" for p in path_params):
        return None
    required = _required_js_fields(ep.create_op)
    candidates = [f for f in required if f != key and
                  _schema_for_field(ep, f).get("type") == "string"]
    if len(candidates) != 1:
        return None
    candidate = candidates[0]
    for response in ep.create_op.op.success_responses:
        for schema in response.media_types.values():
            props = schema.get("properties", {}) if isinstance(schema, dict) else {}
            if any(safe_identifier(name) == candidate and isinstance(value, dict) and
                   value.get("type") == "string" for name, value in props.items()):
                return candidate
    return None


def _documented_create_id_key_alias(ep: EntityPlan) -> Optional[tuple[str, str]]:
    """Map a numeric/string item path key to the documented POST response ID.

    For example an item GET with {item_id} and a POST returning {id: 42}.
    Require matching scalar shapes on the path, POST and GET responses, and
    never substitute an ID that was supplied in the create request itself.
    The generated story still verifies the derived path with an item GET.
    """
    if (not ep.create_op or not ep.get_op or len(ep.key.fields) != 1 or
            ep.create_op.op.path != ep.entity.collection_path or
            ep.get_op.op.path != ep.entity.item_path):
        return None
    key_name = safe_identifier(ep.key.fields[0])
    if key_name == "id" or not key_name.lower().endswith("id"):
        return None
    if ep.get_op.op.path.rstrip('/').rsplit('/', 1)[-1] != '{' + ep.key.fields[0] + '}':
        return None
    if key_name in _required_js_fields(ep.create_op):
        return None
    path_shapes = {_id_shape(param.schema) for param in ep.get_op.op.path_params
                   if safe_identifier(param.name) == key_name}
    path_shapes.discard(None)
    if len(path_shapes) != 1:
        return None
    shape = next(iter(path_shapes))
    if shape not in {("integer", None), ("integer", "int32"),
                     ("integer", "int64"), ("string", None),
                     ("string", "uuid")}:
        return None
    def has_id(op) -> bool:
        return any(_id_shape(schema.get("properties", {}).get("id")) == shape
                   for response in op.op.success_responses
                   for schema in response.media_types.values()
                   if isinstance(schema, dict))
    if not has_id(ep.create_op) or not has_id(ep.get_op):
        return None
    return key_name, "id"


def _possibly_path_changing_field(ep: EntityPlan, op_plan) -> Optional[str]:
    """Conservatively flag a writable resource name used with a string path key.

    The create alias is the stronger proof. Where a composite item path has a
    string final key with a different name (for example {repo}), a writable
    `name` echoed by the item GET can still change that key. Without runtime
    rebinding it must remain a skipped candidate, never a tested witness.
    """
    alias = _long_create_key_alias(ep)
    if alias:
        return alias
    if not ep.get_op or op_plan.op.path != ep.get_op.op.path:
        return None
    last = ep.get_op.op.path.rstrip("/").rsplit("/", 1)[-1]
    if not (last.startswith("{") and last.endswith("}")):
        return None
    key = last[1:-1]
    if not any(p.name == key and p.schema.get("type") == "string"
               for p in ep.get_op.op.path_params):
        return None
    if _schema_for_op_field(op_plan, "name").get("type") != "string":
        return None
    for response in ep.get_op.op.success_responses:
        for schema in response.media_types.values():
            props = schema.get("properties", {}) if isinstance(schema, dict) else {}
            if isinstance(props.get("name"), dict) and props["name"].get("type") == "string":
                return "name"
    return None


def _state_field(ep: EntityPlan, long_interleaving: bool = False) -> str:
    base = to_camel(ep.entity.plural_display_name)
    if long_interleaving:
        import hashlib
        return base + "_" + hashlib.sha256(ep.entity.key.encode("utf-8")).hexdigest()[:10]
    return base


def render_state_tracker(entity_plans: List[EntityPlan],
                         long_interleaving: bool = False) -> str:
    creators = [ep for ep in entity_plans if ep.create_op]
    fields = ", ".join(f"{_state_field(ep, long_interleaving)}: []" for ep in creators)
    wait_sets = ", ".join(f"matchAny{identifier_suffix(ep.entity.plural_display_name)}Added()" for ep in creators)
    lines = [
        "// ==============================================================================",
        "// STATE TRACKER (contract-derived: tracks identifiers returned by create operations)",
        "// ==============================================================================",
        f"const STATE = {{ {fields} }};",
        "",
        'bthread("monitor:StateTracker", function() {',
        "    while (true) {",
        f"        let e = sync({{ waitFor: [{wait_sets}] }});",
    ]
    for i, ep in enumerate(creators):
        key0 = ep.key.fields[0] if len(ep.key.fields) == 1 else None
        cond = "if" if i == 0 else "else if"
        # Dispatch on the unique __entityKey tag embedded in the event
        # data, not on description-text prefix matching alone: two
        # different entities can share the exact same OpenAPI summary
        # (confirmed on NetBox -- 'Interface' and 'VMInterface' both
        # document their create op as "Post a list of interface
        # objects."), which made this if/else-if chain permanently
        # misattribute the second entity's events to the first,
        # leaving its own STATE array empty forever.
        lines.append(f'        {cond} (e.data && e.data["__entityKey"] === {js_string(ep.entity.key)}) {{')
        if key0:
            js_key0 = safe_identifier(key0)
            lines.append(f"            STATE.{_state_field(ep, long_interleaving)}.push(e.data.{js_key0});")
        else:
            lines.append(f"            STATE.{_state_field(ep, long_interleaving)}.push(e.data);")
        lines.append("        }")
    lines.append("    }")
    lines.append("});")
    return "\n".join(lines)


def _value_js(value) -> str:
    import json as _json
    return _json.dumps(value)


def _dependency_assignment_expr(js_field: str, target_ep: EntityPlan, field_schema: Dict) -> str:
    """Render a captured dependency value in the request shape required by OpenAPI.

    Scalar FK fields (e.g. ``authorId``) consume the captured key directly.
    Nested reference objects (e.g. ``site: {id: ...}``) wrap that same runtime
    key in the documented object shape.  Schema-aware dependency inference only
    accepts single-key nested references, so this renderer intentionally mirrors
    that conservative boundary.
    """
    captured = f'captured[{js_string(js_field)}]'
    if isinstance(field_schema, dict) and field_schema.get("type") == "array":
        items = field_schema.get("items", {})
        if isinstance(items, dict) and items.get("type") in ("string", "integer", "number"):
            return "[" + captured + "]"
    if isinstance(field_schema, dict) and field_schema.get("type") == "object":
        props = field_schema.get("properties", {})
        if isinstance(props, dict) and len(target_ep.key.fields) == 1:
            raw_key = target_ep.key.fields[0]
            if raw_key in props:
                return "{" + js_string(raw_key) + ": " + captured + "}"
    return captured


def _dependency_instance_index(instance: int, dependency_position: int, count: int) -> int:
    """Deterministic generic fan-out/cross-binding schedule."""
    if instance == 1:
        return 1
    # Instances 2--3 vary the first dependency while every other dependency
    # remains shared. Instances 4--5 keep dependency 0 shared and vary every
    # remaining dependency together. With only five ordinary CRUD instances,
    # this guarantees three-way fan-out on dependency 0 and cross-binding on
    # every additional dependency, including entities with 3+ foreign keys.
    value = 2 + ((instance - 2) % 2)
    if instance <= 3:
        return min(value, count) if dependency_position == 0 else 1
    return 1 if dependency_position == 0 else min(value, count)


def _required_js_fields(op_plan) -> set:
    required = {safe_identifier(p.name) for p in op_plan.op.parameters if p.required}
    if op_plan.op.request_body:
        _media_type, selected_schema = select_request_variant(op_plan.op)
        selected_schema = _merge_all_of(selected_schema) if isinstance(selected_schema, dict) else {}
        schema_required = selected_schema.get("required", [])
        required.update(safe_identifier(name) for name in schema_required)
        properties = selected_schema.get("properties", {}) if isinstance(selected_schema, dict) else {}
        if op_plan.kind == "create":
            for name, schema in properties.items():
                if isinstance(schema, dict) and schema.get("minLength", 0) >= 1:
                    required.add(safe_identifier(name))
    return required


def _requires_unavailable_binary_transport(op_plan) -> bool:
    """Do not claim a valid multipart binary request from JSON serialization.

    An OpenAPI `format: binary` property describes the transport shape, but
    supplies neither actual file bytes nor a file format accepted by the SUT.
    A generator cannot establish the resulting resource using JSON.stringify.
    """
    media, schema = select_request_variant(op_plan.op)
    if not media or media.split(";", 1)[0].lower() != "multipart/form-data":
        return False
    if not isinstance(schema, dict):
        return False
    properties = schema.get("properties", {})
    return any(isinstance(field, dict) and field.get("format") == "binary"
               for field in properties.values())


def _positive_mutation_choices(op_plan):
    """Choose one conservative writable field when an update schema has no
    formally required property.  This keeps the positive operation non-empty
    without combining unrelated optional fields."""
    if op_plan.op.method not in ("POST", "PUT", "PATCH"):
        return []
    _media_type, schema = select_request_variant(op_plan.op)
    properties = schema.get("properties", {}) if isinstance(schema, dict) else {}
    ranked = []
    for raw_name, field_schema in properties.items():
        if not isinstance(field_schema, dict) or field_schema.get("readOnly"):
            continue
        if field_schema.get("nullable"):
            continue
        kind = field_schema.get("type")
        if kind not in ("boolean", "string", "integer", "number"):
            continue
        js_name = safe_identifier(raw_name)
        if js_name == "id" or js_name.lower().endswith("id"):
            continue
        rank = {"boolean": 0, "string": 1, "integer": 2, "number": 3}[kind]
        ranked.append((rank, js_name, raw_name, field_schema))
    return sorted(ranked, key=lambda item: (item[0], item[1]))


def _positive_mutation_choice(op_plan):
    choices = _positive_mutation_choices(op_plan)
    return choices[0] if choices else None


def _long_update_choices(op_plan, owner: Optional[EntityPlan], seed: int) -> List[tuple]:
    """Multiple contract-derived, independently checked fields per live entity.

    The item GET must expose the same writable field and type. This is a
    schema-only filter; a server may still reject a value because of an
    invariant not expressed in OpenAPI, in which case the story is recorded
    as unsuccessful and never counted as a successful witness.
    """
    if not owner or not owner.create_op or not owner.get_op or not op_plan.story_dependencies:
        return []
    observed = {}
    for response in owner.get_op.op.success_responses:
        for schema in response.media_types.values():
            observed.update(schema.get("properties", {}) if isinstance(schema, dict) else {})
    candidates = []
    for choice in _positive_mutation_choices(op_plan):
        _, js_field, raw_field, field_schema = choice
        field_schema = _contract_described_field_schema(field_schema)
        choice = (choice[0], js_field, raw_field, field_schema)
        response_field = observed.get(raw_field)
        if js_field not in op_plan.params or not isinstance(response_field, dict):
            continue
        if response_field.get("type") != field_schema.get("type"):
            continue
        if _runtime_distinct_assignment(js_field, raw_field, field_schema, "__beforeMutation"):
            candidates.append(choice)
    if not candidates:
        return []
    # Keep a core of reversible booleans on every seed. Rotating across all
    # fields can accidentally choose only constrained strings in a contract
    # that has many fields, losing every otherwise executable story.
    def rotate(items):
        offset = seed % len(items) if items else 0
        return items[offset:] + items[:offset]

    booleans = rotate([choice for choice in candidates
                       if choice[3].get("type") == "boolean"])
    others = rotate([choice for choice in candidates
                     if choice[3].get("type") != "boolean"])
    core = booleans[:4]
    return (core + others[:6 - len(core)] + booleans[len(core):])[:6]


def _positive_mutation_field(op_plan) -> Optional[str]:
    """Compatibility wrapper used by older tests and profiles."""
    choice = _positive_mutation_choice(op_plan)
    return choice[1] if choice else None


def _runtime_distinct_assignment(js_name: str, raw_name: str, schema: Dict,
                                 baseline_var: str) -> Optional[str]:
    """Return contract-derived JS that avoids a no-op mutation.

    The current value comes from the operation's OpenAPI-derived item GET.
    No application-specific field meaning or value is used.
    """
    current = f'{baseline_var}.body[{js_string(raw_name)}]'
    guard = (f'{baseline_var} && {baseline_var}.body && '
             f'{current} !== undefined && {current} !== null')
    kind = schema.get("type") if isinstance(schema, dict) else None
    if kind == "boolean":
        return f'  if ({guard} && typeof {current} === "boolean") {{ {js_name} = !{current}; }}'
    enum = schema.get("enum", []) if isinstance(schema, dict) else []
    if isinstance(enum, list) and len(enum) >= 2:
        first, second = _value_js(enum[0]), _value_js(enum[1])
        return f'  if ({guard}) {{ {js_name} = ({current} === {first}) ? {second} : {first}; }}'
    if kind in ("integer", "number"):
        minimum = schema.get("minimum") if isinstance(schema, dict) else None
        maximum = schema.get("maximum") if isinstance(schema, dict) else None
        low = _value_js(minimum) if minimum is not None else "null"
        high = _value_js(maximum) if maximum is not None else "null"
        return (
            f'  if ({guard} && typeof {current} === "number") {{ '
            f'if ({high} === null || {current} < {high}) {{ {js_name} = {current} + 1; }} '
            f'else if ({low} === null || {current} > {low}) {{ {js_name} = {current} - 1; }} }}'
        )
    if kind == "string" and schema.get("format") == "email":
        # A no-op fallback must retain the format inferred from the public
        # request field description; appending a suffix after the domain
        # would turn an otherwise valid update into an invalid request.
        return (f'  if ({guard} && String({js_name}) === String({current})) {{ '
                f'{js_name} = String({js_name}).replace("@", "+sbt@"); }}')
    if kind == "string" and schema.get("maxLength") is None:
        return (f'  if ({guard} && String({js_name}) === String({current})) {{ '
                f'{js_name} = String({js_name}) + "_sbt"; }}')
    return None


def _operation_field_should_be_seeded(op_plan, js_field: str) -> bool:
    """Whether a generic positive story may invent a value for a field.

    The decision uses only OpenAPI structure. Required path, transport and
    body inputs are populated. Optional transport inputs are omitted. Optional
    body inputs are populated only when writable, scalar and non-nullable;
    optional identifiers must instead be supplied by a real dependency.
    """
    op = op_plan.op
    for parameter in op.path_params:
        if safe_identifier(parameter.name) == js_field:
            return True
    for parameter in op.query_params + op.header_params + op.cookie_params:
        if safe_identifier(parameter.name) == js_field:
            return bool(parameter.required)
    if op.request_body:
        for variant in op.request_body.variants:
            schema = variant.schema if isinstance(variant.schema, dict) else {}
            required = {safe_identifier(name) for name in schema.get("required", [])}
            properties = schema.get("properties", {})
            if not isinstance(properties, dict):
                continue
            for raw_name, field_schema in properties.items():
                if safe_identifier(raw_name) != js_field:
                    continue
                field_schema = field_schema if isinstance(field_schema, dict) else {}
                if field_schema.get("readOnly") is True:
                    return False
                if js_field in required:
                    return True
                if field_schema.get("nullable") is True:
                    return False
                if js_field == "id" or js_field.lower().endswith("id"):
                    return False
                return field_schema.get("type") not in ("object", "array", None)
    return False


def _operation_story_executable(op_plan) -> bool:
    """Do not issue a positive request with an invented required path id."""
    required_path = {safe_identifier(p.name) for p in op_plan.op.path_params if p.required}
    bound = {field for field, _target in op_plan.story_dependencies}
    return required_path.issubset(bound)


def _op_args(op_plan, values: Dict[str, str]) -> str:
    return ", ".join(values.get(param, "undefined") for param in op_plan.params)


def _single_key_var(entity_plan: EntityPlan, role: str) -> Tuple[str, str]:
    raw_key = entity_plan.key.fields[0]
    return safe_identifier(raw_key), f"__{role}Id"


def _minimal_values(op_plan, prefix: str, seed: int,
                    dependency_values: Optional[Dict[str, str]] = None,
                    carry_values: Optional[Dict[str, str]] = None) -> Tuple[List[str], Dict[str, str]]:
    """Produce contract-derived values only for required/minLength fields.

    The returned mapping is suitable for a full generated interface signature;
    every omitted optional argument becomes JavaScript ``undefined`` and is
    therefore excluded by the interface serializer.
    """
    dependency_values = dependency_values or {}
    carry_values = carry_values or {}
    required = _required_js_fields(op_plan)
    declarations: List[str] = []
    values: Dict[str, str] = dict(dependency_values)
    for param in op_plan.params:
        if param in values:
            continue
        if param in carry_values:
            values[param] = carry_values[param]
            continue
        if param not in required:
            continue
        schema = _schema_for_op_field(op_plan, param)
        value = generate_value(schema, seed, f"validated-lifecycle.{prefix}.{param}", for_request=True)
        variable = f"__{prefix}_{param}"
        declarations.append(f"  let {variable} = {_value_js(value)};")
        values[param] = variable
    return declarations, values


def _select_update_operation(entity_plan: EntityPlan):
    """Choose a deterministic update and a safe scalar field from OpenAPI.

    PUT is preferred because its ordinary object schema is generally more
    portable than JSON Patch arrays.  Candidate fields exclude identifiers and
    relationship-shaped names; booleans are preferred, then enums, then simple
    strings/numbers.
    """
    operations = [op for op in entity_plan.ops if op.kind == "update" and op.op.request_body]
    operations.sort(key=lambda op: (0 if op.op.method == "PUT" else 1, op.op.path, op.js_name))
    key_names = {_norm_key(name) for name in entity_plan.key.fields}
    ranked = []
    for operation in operations:
        schemas = _request_body_schemas_for_operation(operation)
        for raw_name, schema in schemas.items():
            normalized = _norm_key(raw_name)
            if (normalized in key_names or normalized.endswith("id") or
                    schema.get("readOnly") or schema.get("type") in ("object", "array")):
                continue
            if schema.get("type") == "boolean":
                rank = 0
            elif schema.get("enum"):
                rank = 1
            elif schema.get("type") == "string" and not schema.get("format"):
                rank = 2
            elif schema.get("type") in ("integer", "number"):
                rank = 3
            else:
                continue
            method_rank = 0 if operation.op.method == "PUT" else 1
            ranked.append((rank, method_rank, safe_identifier(raw_name), raw_name, schema, operation))
    if not ranked:
        return None
    ranked.sort(key=lambda item: (item[0], item[1], item[2], item[5].js_name))
    return ranked[0]


def _norm_key(value: str) -> str:
    return "".join(ch for ch in value.lower() if ch.isalnum())


def _request_body_schemas_for_operation(op_plan) -> Dict[str, Dict]:
    _media_type, schema = select_request_variant(op_plan.op)
    props = schema.get("properties", {}) if isinstance(schema, dict) else {}
    if isinstance(props, dict) and props:
        return {name: value for name, value in props.items() if isinstance(value, dict)}
    return {}


def _association_operations(child: EntityPlan, auxiliary_key: str):
    posts = [op for op in child.ops
             if op.kind == "action" and op.op.method == "POST"
             and child.entity.key in {target for _, target in op.story_dependencies}
             and auxiliary_key in {target for _, target in op.story_dependencies}]
    for attach in sorted(posts, key=lambda op: (op.op.path, op.js_name)):
        listing = next((op for op in child.ops
                        if op.kind == "action" and op.op.method == "GET"
                        and op.op.path == attach.op.path), None)
        detach = next((op for op in child.ops
                       if op.kind == "action" and op.op.method == "DELETE"
                       and op.op.path.startswith(attach.op.path + "/")
                       and auxiliary_key in {target for _, target in op.story_dependencies}), None)
        if listing and detach:
            return attach, listing, detach
    return None


def _select_validated_lifecycle(plan: Plan):
    by_key = {ep.entity.key: ep for ep in plan.entities}
    complete = [ep for ep in plan.entities
                if ep.create_op and ep.get_op and ep.delete_op and len(ep.key.fields) == 1]
    for child in sorted(complete, key=lambda ep: ep.entity.key):
        update = _select_update_operation(child)
        if not update:
            continue
        for dependency in child.dependencies:
            parent = by_key.get(dependency.target)
            if parent not in complete:
                continue
            for auxiliary in sorted(complete, key=lambda ep: ep.entity.key):
                if auxiliary.entity.key in (child.entity.key, parent.entity.key):
                    continue
                association = _association_operations(child, auxiliary.entity.key)
                if association:
                    return parent, child, auxiliary, dependency, update, association
    return None


